"""Generate docs/RESULTS.md from runs/ — the only way results enter the write-up.

The latest run of each (method, split) is reported; older runs stay in runs/ for the record.
usage: python src/eval/report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "runs"
COLS = ["recall@5%", "recall@1%", "genuine_flag@5%", "auroc", "paired_win"]


def fmt(v):
    p, lo, hi = v
    return "—" if p is None else f"{p:.3f} [{lo:.3f}, {hi:.3f}]"


def main():
    latest = {}
    for run in sorted(RUNS.glob("*/*/run.json")):
        r = json.loads(run.read_text())
        latest[(r["method"], r["split"])] = (r, json.loads((run.parent / "metrics.json").read_text()))
    lines = ["# Results", "", "Generated by `src/eval/report.py` from `runs/` — do not edit by hand.",
             "Higher score = more suspicious. Threshold for @b: top b of natural (presumed honest) submissions.",
             "Brackets: 95% user-cluster bootstrap interval.", ""]
    for split in ("test", "val"):
        rows = [(m, r, mt) for (m, s), (r, mt) in sorted(latest.items()) if s == split]
        if not rows:
            continue
        lines += [f"## {split}", "", "| method | " + " | ".join(COLS) + " | coverage | users |", "|---" * (len(COLS) + 3) + "|"]
        for m, r, mt in rows:
            a = mt["all"]
            lines.append(f"| {m} | " + " | ".join(fmt(a[k]) for k in COLS) + f" | {a['coverage']:.3f} | {a['n_users']} |")
        lines.append("")
        for m, r, mt in rows:
            lines += [f"<details><summary>{m} — by corpus and difficulty</summary>", "",
                      "| scope | recall@5% | auroc | paired_win | n_pos |", "|---|---|---|---|---|"]
            for scope, v in mt.items():
                if scope != "all":
                    lines.append(f"| {scope} | {fmt(v['recall@5%'])} | {fmt(v['auroc'])} | {fmt(v['paired_win'])} | {v['n_pos']} |")
            lines += ["", f"run: `{r['at']}`, frame `{r['frame']}`, script `{r['script']}`", "</details>", ""]
    (ROOT / "docs/RESULTS.md").write_text("\n".join(lines) + "\n")
    print(f"docs/RESULTS.md: {len(latest)} (method, split) entries")


if __name__ == "__main__":
    main()
